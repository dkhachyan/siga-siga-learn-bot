"""Перечисления домена.

Значения пишутся в базу как строки, поэтому переименование любого из них —
это миграция. Добавлять новые можно свободно, менять существующие — нет.
"""

from __future__ import annotations

from enum import StrEnum


class UserState(StrEnum):
    """Где пользователь находится в жизненном цикле продукта."""

    NEW = "new"
    """Нажал /start, ещё не прошёл онбординг."""

    ONBOARDING = "onboarding"
    """Отвечает на вопросы про уровень, окно и частоту."""

    ACTIVE = "active"
    """Есть активная пачка слов, бот пишет по расписанию."""

    PAUSED = "paused"
    """Сам поставил на паузу — расписание не срабатывает, период не тикает."""

    FINISHED = "finished"
    """Период закончился, новая пачка ещё не загружена."""


class Level(StrEnum):
    """Уровень греческого. Влияет на сложность реплик в эпизодах."""

    A1 = "A1"
    A2 = "A2"
    B1 = "B1"
    B2 = "B2"


class PackStatus(StrEnum):
    """Состояние пачки слов."""

    DRAFT = "draft"
    """Слова разобраны, но человек ещё не нажал «Всё верно»."""

    ACTIVE = "active"
    """Пачка в работе: по ней идут эпизоды."""

    ARCHIVED = "archived"
    """Период закончился или пачку отменили."""


class PartOfSpeech(StrEnum):
    """Часть речи. Определяет, какие поля слова вообще имеют смысл."""

    NOUN = "noun"
    """Существительное: есть артикль и род."""

    VERB = "verb"
    """Глагол: есть форма 1 л. ед. ч. наст. вр."""

    ADJECTIVE = "adjective"
    ADVERB = "adverb"
    PHRASE = "phrase"
    """Устойчивое выражение целиком, а не одно слово."""

    OTHER = "other"
    """Предлоги, союзы, частицы — всё, что не требует своей грамматики."""


class Gender(StrEnum):
    """Род существительного. Для остальных частей речи — None."""

    MASCULINE = "m"
    FEMININE = "f"
    NEUTER = "n"


class EpisodeIntent(StrEnum):
    """Тип эпизода (§5.3). Выбирается по боксу самого слабого целевого слова."""

    D1 = "D1"
    """Знакомство: Ник употребляет слово сам и проверяет, понято ли."""

    D2 = "D2"
    """Употребление в ответе: вопрос, на который без слова не ответить."""

    D3 = "D3"
    """Пользователь сам задаёт вопрос с этим словом."""

    D4 = "D4"
    """Сценка с ролью."""

    D5 = "D5"
    """Возврат к слову из архива."""


class EpisodeStatus(StrEnum):
    """Жизненный цикл эпизода."""

    PENDING = "pending"
    """Рамка сгенерирована, первая реплика ещё не отправлена."""

    OPEN = "open"
    """Идёт разговор: ждём ответа пользователя."""

    CLOSED = "closed"
    """Дошёл до конца — по словам, по ходам или по просьбе человека."""

    ABANDONED = "abandoned"
    """До конца не дошёл не по вине человека: истёк TTL или отправка не
    состоялась вовсе. Слова возвращаются в пул без штрафа (FR-SCH-4, FR-SCH-6)."""


class EventType(StrEnum):
    """Что именно должно произойти в назначенный момент (§5.6)."""

    EPISODE = "episode"
    """Отправить первую реплику готового эпизода."""

    NUDGE = "nudge"
    """Мягко напомнить о себе, если человек молчит 40 минут (FR-SCH-6)."""


class EventStatus(StrEnum):
    """Судьба одного события расписания."""

    PENDING = "pending"
    """Ждёт своего часа."""

    SENT = "sent"
    """Отправлено. Статус меняется в той же транзакции, что и отправка (NFR-1)."""

    SKIPPED = "skipped"
    """Момент пришёл, но отправлять не стали: шёл другой разговор, окно
    закрылось или человек поставил расписание на паузу."""

    EXPIRED = "expired"
    """Опоздали больше чем на полтора часа (FR-SCH-4)."""


class Verdict(StrEnum):
    """Оценка употребления целевого слова в одном ответе (§5.4)."""

    CORRECT = "correct"
    """Слово употреблено верно."""

    ALMOST = "almost"
    """Опечатка или неверная форма правильного слова — рекаст, бокс не растёт."""

    INCORRECT = "incorrect"
    """Не то слово или потерян смысл."""


class ErrorType(StrEnum):
    """Чем именно ошибся человек — нужно для `recurring_errors` в памяти (§5.5)."""

    CASE = "case"
    """Падеж."""

    GENDER = "gender"
    ARTICLE = "article"
    VERB_FORM = "verb_form"
    ACCENT = "accent"
    """Ударение — в греческом это часть орфографии, а иногда и значения."""

    SPELLING = "spelling"
    WRONG_WORD = "wrong_word"
    LATIN = "latin"
    """Написано латиницей вместо греческого (FR-CHK-3)."""

    OTHER = "other"


class WordSource(StrEnum):
    """Откуда слово попало в базу — нужно для разбора жалоб на качество."""

    TEXT = "text"
    """Человек набрал список текстом."""

    PHOTO = "photo"
    """Распознано с фотографии."""

    FILE = "file"
    """Загружен .txt или .csv."""

    MANUAL = "manual"
    """Добавлено по одному на экране подтверждения."""
